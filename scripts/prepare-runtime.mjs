import { readFile, writeFile, mkdir } from "node:fs/promises";
import { resolve } from "node:path";

// Public, immutable build metadata only. Parse once during isolate startup,
// rather than charging each cold request for the full asset manifest.
const stage = process.argv.find(value => value.startsWith("--staging="))?.slice(10);
if (stage && !/^\.staging-\d+$/.test(stage)) throw new Error("Invalid staging directory");
const directory = resolve(import.meta.dirname, "../data", stage || "generated");
let manifest;
try {
  manifest = JSON.parse(
    await readFile(resolve(directory, "manifest.json"), "utf8"),
  );
} catch (error) {
  if (error.code !== "ENOENT") throw error;
  manifest = {
    schemaVersion: 1,
    version: "unconfigured",
    builtAt: "",
    profile: "none",
    sources: [],
  };
}
if (manifest.schemaVersion !== 1 || !Array.isArray(manifest.sources))
  throw new Error("Invalid build manifest");
const compact = {
  ...manifest,
  sources: manifest.sources.map(({ shards, ...source }) => ({
    ...source,
    shards: (shards || []).map((s) => [
      s.id,
      s.family,
      s.start,
      s.end,
      s.count,
      s.byteLength,
      s.sha256,
    ]),
  })),
};
const json = JSON.stringify(compact);
if (Buffer.byteLength(json) > 2 * 1024 * 1024)
  throw new Error("Worker metadata budget exceeded");
const content = `// Generated by scripts/prepare-runtime.mjs. No visitor data.\nconst manifest = JSON.parse(${JSON.stringify(json)});\nfor (const source of manifest.sources) source.shards = source.shards.map((s: [string, number, string, string, number, number, string]) => ({id:s[0],family:s[1],start:s[2],end:s[3],count:s[4],byteLength:s[5],sha256:s[6],path:"/_intel/"+source.id+"/"+s[0]+".bin"}));\nexport default manifest as unknown;\n`;
await mkdir(directory, { recursive: true });
const target = resolve(directory, "worker-snapshot.ts");
let previous;
try {
  previous = await readFile(target, "utf8");
} catch (error) {
  if (error.code !== "ENOENT") throw error;
}
if (previous !== content) await writeFile(target, content);
